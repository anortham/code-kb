/// Whether a library type takes type arguments: `NonGeneric` (`Exception`), `Generic`
/// (`List<T>`), or `Both` (`Action` and `Action<T>`).
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Arity {
    NonGeneric,
    Generic,
    Both,
}

impl Arity {
    pub(super) fn fits(self, generic: bool) -> bool {
        match self {
            Self::NonGeneric => !generic,
            Self::Generic => generic,
            Self::Both => true,
        }
    }
}

